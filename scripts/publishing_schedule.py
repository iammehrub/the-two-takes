"""Weekly Two Takes publishing allocation, using Bangladesh-local weekdays.

Long videos: Tuesday, Thursday, Saturday.
Shorts: Monday, Wednesday, Friday, Sunday.
The offsets below allocate the four Shorts to the three long-video production runs.
"""

from __future__ import annotations


# datetime.weekday(): Monday=0 ... Sunday=6.
SHORT_OFFSETS_BY_LONG_VIDEO_WEEKDAY: dict[int, tuple[int, ...]] = {
    1: (1, 3),  # Tuesday episode -> Wednesday and Friday Shorts.
    3: (3,),    # Thursday episode -> Sunday Short.
    5: (2,),    # Saturday episode -> following Monday Short.
}


def short_publish_offsets(episode_weekday: int) -> tuple[int, ...]:
    """Return day offsets for Shorts generated by a long-video run."""
    if not isinstance(episode_weekday, int) or not 0 <= episode_weekday <= 6:
        raise ValueError("episode_weekday must be an integer from 0 (Monday) to 6 (Sunday)")
    return SHORT_OFFSETS_BY_LONG_VIDEO_WEEKDAY.get(episode_weekday, ())
